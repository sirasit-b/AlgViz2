/* ==========================================================================
   AlgoViz build — standalone PHP site.
   Source of truth (src/):
     core.head.html            → <style> …CSS…  (assets/algoviz.css)
     core.body.html            → widget markup (assets/app.html)
                                  + engine IIFE  (assets/algoviz.js), with markers
                                    @@RENDERERS_EXT@@  and  @@CONTENT@@
     renderers/*.js            → extra renderer families → @@RENDERERS_EXT@@
     content/ ** / *.js        → extra modules           → @@CONTENT@@
   Outputs:
     assets/algoviz.css        (linked by partials/head.php)
     assets/algoviz.js         (loaded by partials/footer.php)
     assets/app.html           (included by index.php)
     config/topics.php         (auto-generated metadata for PHP SEO/routing)
     preview.html              (self-contained, for file:// testing — uses hash routing)
   PHP files (index.php, .htaccess, partials/*.php, config/taxonomy.php) are hand-authored.
   Run:  node build/build.mjs      Add a module: drop a .js in src/content/<domain>/ + rebuild.
   ========================================================================== */
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const SRC  = join(ROOT, 'src');
const rd = (p) => readFileSync(p, 'utf8');
const ensure = (p) => { try { mkdirSync(p, { recursive: true }); } catch {} };

function walk(dir){
  let out = [], entries = [];
  try { entries = readdirSync(dir); } catch { return out; }
  for (const e of entries.sort()){
    const p = join(dir, e);
    if (statSync(p).isDirectory()) out = out.concat(walk(p));
    else if (p.endsWith('.js')) out.push(p);
  }
  return out;
}
const fragment = (f) => `\n/* ===== ${relative(ROOT, f).replace(/\\/g,'/')} ===== */\n` + rd(f) + '\n';

/* ---- CSS ---- */
const headHtml = rd(join(SRC, 'core.head.html'));
const css = (/<style>([\s\S]*?)<\/style>/.exec(headHtml) || [,''])[1].trim();

/* ---- markup + engine JS from core.body.html ---- */
const bodyHtml = rd(join(SRC, 'core.body.html'));
const cdnIdx = bodyHtml.indexOf('<!-- anime.js');
const markup = bodyHtml.slice(0, cdnIdx).trim();
const sOpen = bodyHtml.indexOf('<script>', cdnIdx >= 0 ? cdnIdx : 0);
const sClose = bodyHtml.indexOf('</script>', sOpen);
let js = bodyHtml.slice(sOpen + '<script>'.length, sClose);

const rendererBlock = walk(join(SRC, 'renderers')).map(fragment).join('') || '/* (none) */';
const contentBlock  = walk(join(SRC, 'content')).map(fragment).join('')  || '/* (none) */';
js = js.replace('/* @@RENDERERS_EXT@@ */', () => rendererBlock)
       .replace('/* @@CONTENT@@ */',       () => contentBlock);

/* ---- parse registered modules → config/topics.php ---- */
const CAT_DOMAIN = { sort:'cs', search:'cs', linear:'cs', tree:'cs', graph:'cs', recur:'cs', net:'cpe', se:'se' };
const positions = [...js.matchAll(/AlgoViz\.register\(\{/g)].map(m => m.index);
const topics = [];
for (let i = 0; i < positions.length; i++){
  const seg = js.slice(positions[i], positions[i+1] ?? js.length);
  const id = (/id:\s*'([\w-]+)'/.exec(seg) || [])[1];
  if (!id) continue;
  const cat  = (/cat:\s*'(\w+)'/.exec(seg) || [])[1] || '';
  const diff = (/difficulty:\s*(\d)/.exec(seg) || [])[1] || '1';
  const th   = (/nameTh:\s*(['"])([\s\S]*?)\1/.exec(seg) || [])[2] || id;
  const en   = (/nameEn:\s*(['"])([\s\S]*?)\1/.exec(seg) || [])[2] || id;
  const blurb= (/blurb:\s*(['"])([\s\S]*?)\1/.exec(seg) || [])[2] || '';
  topics.push({ id, cat, domain: CAT_DOMAIN[cat] || 'cs', diff: +diff, th, en, blurb });
}
const pq = (s) => "'" + String(s).replace(/\\/g,'\\\\').replace(/'/g,"\\'") + "'";
let php = "<?php\n// AUTO-GENERATED by build/build.mjs — do not edit by hand.\nreturn [\n";
for (const t of topics)
  php += `  ${pq(t.id)} => ['cat'=>${pq(t.cat)}, 'domain'=>${pq(t.domain)}, 'th'=>${pq(t.th)}, 'en'=>${pq(t.en)}, 'blurb'=>${pq(t.blurb)}, 'diff'=>${t.diff}],\n`;
php += "];\n";

/* ---- write ---- */
ensure(join(ROOT, 'assets'));
ensure(join(ROOT, 'config'));
writeFileSync(join(ROOT, 'assets', 'algoviz.css'), css);
writeFileSync(join(ROOT, 'assets', 'algoviz.js'),  js);
writeFileSync(join(ROOT, 'assets', 'app.html'),    markup);
writeFileSync(join(ROOT, 'config', 'topics.php'),  php);

const FONTS = '<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin><link href="https://fonts.googleapis.com/css2?family=Noto+Sans+Thai:wght@400;500;600;700;800&family=JetBrains+Mono:wght@400;600;700&display=swap" rel="stylesheet">';
const CDN = '<script src="https://cdnjs.cloudflare.com/ajax/libs/animejs/3.2.2/anime.min.js"></script>\n<script defer src="https://cdnjs.cloudflare.com/ajax/libs/three.js/r128/three.min.js"></script>';
const preview = `<!DOCTYPE html>\n<html lang="th">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1">\n<title>AlgoViz · preview (hash mode)</title>\n${FONTS}\n<style>\n${css}\n</style>\n</head>\n<body style="margin:0;background:#0A0A0A">\n${markup}\n${CDN}\n<script>\n${js}\n</script>\n</body>\n</html>\n`;
writeFileSync(join(ROOT, 'preview.html'), preview);

console.log(`AlgoViz build ✓  ${topics.length} topics`);
console.log('  assets/algoviz.css, assets/algoviz.js, assets/app.html');
console.log('  config/topics.php (generated), preview.html');
